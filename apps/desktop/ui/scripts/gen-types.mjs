// Generates src/lib/ipc/generated.ts from the Rust JSON Schema (`qw schema`).
// Run with `pnpm gen:types`; CI runs it and fails when the committed file differs.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', '..');
const out = join(root, 'apps', 'desktop', 'ui', 'src', 'lib', 'ipc', 'generated.ts');

const json = execFileSync('cargo', ['run', '--quiet', '--locked', '-p', 'quirewise-cli', '--', 'schema'], {
  cwd: root,
  encoding: 'utf8',
  maxBuffer: 16 * 1024 * 1024,
});
const schema = JSON.parse(json);

const banner = [
  '/* Generated by scripts/gen-types.mjs from `qw schema`. Do not edit by hand. */',
  '/* eslint-disable */',
].join('\n');

const ts = await compile(schema, 'IpcTypes', {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: true },
});
writeFileSync(out, ts.replaceAll('\r\n', '\n'));
console.log(`wrote ${out}`);
